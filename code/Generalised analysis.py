# 05_generalisation_analysis.py
# Part 5 — Generalisation analysis (Rifa)
# Compare test-set performance, investigate class errors and feature differences

from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.metrics import confusion_matrix, top_k_accuracy_score
from sklearn.decomposition import PCA
from scipy.spatial.distance import cdist

plt.rcParams.update({"font.size": 11})

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data" / "processed"
OUT  = ROOT / "data" / "output"
OUT.mkdir(parents=True, exist_ok=True)

SEED = 7
rng  = np.random.default_rng(SEED)

# ---------------------------------------------------------------------------
# 1. Load data & predictions
# ---------------------------------------------------------------------------
# Expected prediction files produced by teammates (adjust names if needed):
#   preds_A_test1.npy, preds_A_test2.npy   (Classifier A – regularised linear)
#   preds_B_test1.npy, preds_B_test2.npy   (Classifier B – small MLP)
#   preds_C_test1.npy, preds_C_test2.npy   (Classifier C – nearest-centroid / PCA)
#
# Each file should be shape (n_samples,) of predicted class indices (0-999)
# or shape (n_samples, 1000) of logits / probabilities (the script handles both).

def load_preds(name, test):
    path = OUT / f"preds_{name}_{test}.npy"
    if not path.exists():
        raise FileNotFoundError(
            f"Missing {path}. Ask teammates to save their final predictions "
            f"as numpy arrays of shape (n,) or (n, 1000)."
        )
    p = np.load(path)
    if p.ndim == 2:                       # logits or probabilities
        return p.argmax(axis=1), p
    return p, None

# Ground-truth labels
y1 = np.load(PROC / "test1_y.npy")
y2 = np.load(PROC / "test2_y.npy")

# Features (for the feature-shift analysis)
X1 = np.load(PROC / "test1_X.npy", mmap_mode="r")
X2 = np.load(PROC / "test2_X.npy", mmap_mode="r")

classifiers = ["A", "B", "C"]
names = {
    "A": "Regularised Linear",
    "B": "Small MLP",
    "C": "Nearest-Centroid / PCA",
}

preds = {}
probs  = {}
for clf in classifiers:
    preds[clf] = {}
    probs[clf] = {}
    for test, y in [("test1", y1), ("test2", y2)]:
        p, pr = load_preds(clf, test)
        preds[clf][test] = p
        probs[clf][test] = pr

print("Loaded predictions for", classifiers)
print("test1 size:", len(y1), "  test2 size:", len(y2))

# ---------------------------------------------------------------------------
# 2. Overall accuracy comparison
# ---------------------------------------------------------------------------
def accuracy(y_true, y_pred):
    return (y_true == y_pred).mean()

def top5(y_true, proba):
    if proba is None:
        return np.nan
    return top_k_accuracy_score(y_true, proba, k=5, labels=np.arange(1000))

rows = []
for clf in classifiers:
    for test, y in [("test1", y1), ("test2", y2)]:
        top1 = accuracy(y, preds[clf][test])
        t5   = top5(y, probs[clf][test])
        rows.append({
            "classifier": names[clf],
            "test_set": test,
            "top1": top1,
            "top5": t5,
        })

overall = pd.DataFrame(rows)
overall.to_csv(OUT / "gen_overall_accuracy.csv", index=False)
print("\n=== Overall accuracy ===")
print(overall.round(4).to_string(index=False))

# Gap table
gap = overall.pivot(index="classifier", columns="test_set", values="top1")
gap["gap"] = gap["test1"] - gap["test2"]
gap.to_csv(OUT / "gen_accuracy_gap.csv")
print("\nTop-1 gap (test1 − test2):")
print(gap.round(4))

# ---------------------------------------------------------------------------
# 3. Per-class accuracy & biggest generalisation failures
# ---------------------------------------------------------------------------
def per_class_acc(y_true, y_pred):
    acc = np.zeros(1000)
    for c in range(1000):
        mask = y_true == c
        if mask.sum() > 0:
            acc[c] = (y_pred[mask] == c).mean()
    return acc

class_gaps = {}
for clf in classifiers:
    acc1 = per_class_acc(y1, preds[clf]["test1"])
    acc2 = per_class_acc(y2, preds[clf]["test2"])
    gap  = acc1 - acc2
    class_gaps[clf] = pd.DataFrame({
        "class": np.arange(1000),
        "acc_test1": acc1,
        "acc_test2": acc2,
        "gap": gap,
    })
    class_gaps[clf].to_csv(OUT / f"gen_perclass_{clf}.csv", index=False)

# Classes with largest average gap across models
avg_gap = np.mean([class_gaps[c]["gap"].values for c in classifiers], axis=0)
worst   = np.argsort(avg_gap)[::-1][:20]   # top-20 largest drops

print("\n=== 20 classes with largest average generalisation gap ===")
print(pd.DataFrame({
    "class": worst,
    "avg_gap": avg_gap[worst],
}).round(3).to_string(index=False))

# ---------------------------------------------------------------------------
# 4. Error-pattern / confusion analysis (focus on largest-gap classes)
# ---------------------------------------------------------------------------
# For the three models, look at the most common wrong predictions on the
# classes that drop the most.
focus_classes = worst[:10]

error_summary = []
for clf in classifiers:
    for c in focus_classes:
        mask = (y2 == c) & (preds[clf]["test2"] != c)
        if mask.sum() == 0:
            continue
        wrong = preds[clf]["test2"][mask]
        top_wrong = pd.Series(wrong).value_counts().head(3)
        for pred, cnt in top_wrong.items():
            error_summary.append({
                "classifier": names[clf],
                "true_class": c,
                "predicted_as": pred,
                "count": cnt,
                "frac_of_errors": cnt / mask.sum(),
            })

errors = pd.DataFrame(error_summary)
errors.to_csv(OUT / "gen_error_patterns.csv", index=False)
print("\nError patterns on largest-gap classes saved.")

# ---------------------------------------------------------------------------
# 5. Feature-space analysis – class centroid shift
# ---------------------------------------------------------------------------
# Compute mean feature vector per class on each test set and measure the
# Euclidean / cosine distance between the two centroids.
# This gives direct evidence of distribution shift in the 1024-d space.

def class_centroids(X, y, n_classes=1000):
    cents = np.zeros((n_classes, X.shape[1]), dtype=np.float32)
    counts = np.bincount(y, minlength=n_classes)
    for c in range(n_classes):
        if counts[c] > 0:
            cents[c] = X[y == c].mean(axis=0)
    return cents, counts

cents1, cnt1 = class_centroids(X1, y1)
cents2, cnt2 = class_centroids(X2, y2)

# Only keep classes that appear in both sets
valid = (cnt1 > 0) & (cnt2 > 0)
eucl  = np.linalg.norm(cents1[valid] - cents2[valid], axis=1)
cos   = 1 - np.sum(cents1[valid] * cents2[valid], axis=1) / (
            np.linalg.norm(cents1[valid], axis=1) * np.linalg.norm(cents2[valid], axis=1) + 1e-8)

feat_shift = pd.DataFrame({
    "class": np.where(valid)[0],
    "euclidean": eucl,
    "cosine_dist": cos,
    "n_test1": cnt1[valid],
    "n_test2": cnt2[valid],
})
feat_shift = feat_shift.sort_values("euclidean", ascending=False)
feat_shift.to_csv(OUT / "gen_feature_shift.csv", index=False)

print("\n=== Feature centroid shift (top-10 largest Euclidean) ===")
print(feat_shift.head(10).round(4).to_string(index=False))

# Correlation between feature shift and accuracy gap (evidence for hypothesis)
for clf in classifiers:
    g = class_gaps[clf].set_index("class")["gap"]
    corr = feat_shift.set_index("class")["euclidean"].corr(g)
    print(f"Correlation (Euclidean shift ↔ {names[clf]} gap): {corr:.3f}")

